export const MESSAGES: Record<Locale, Messages> = { en, vi };

const INTL_TAGS: Record<Locale, string> = { en: 'en-GB', vi: 'vi-VN' };

export function intlTag(locale: Locale): string {
  return INTL_TAGS[locale];
}

/** Decimal with the locale's separator: 2.5 → "2.5" in English, "2,5" in Vietnamese. */
export function formatDecimal(locale: Locale, value: number, fractionDigits?: number): string {
  return new Intl.NumberFormat(INTL_TAGS[locale], {
    minimumFractionDigits: fractionDigits ?? 0,
    maximumFractionDigits: fractionDigits ?? 1,
  }).format(value);
}

/** "1 win · 1.33 pts/game", or an empty string before the player has played. */
export function describeRecord(record: PlayerRecord | undefined, t: Messages, locale: Locale): string {
  if (!record || record.games === 0) return '';
  return t.common.record(record.wins, formatDecimal(locale, record.points / record.games, 2));
}

/** "just now", "40 s ago", "12 min ago", "2 h ago" (or the Vietnamese equivalents). */
export function formatAgo(thenMs: number, nowMs: number, t: Messages): string {
  const seconds = Math.max(0, Math.round((nowMs - thenMs) / 1000));
  if (seconds < 5) return t.common.justNow;
  if (seconds < 60) return t.common.secondsAgo(seconds);
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return t.common.minutesAgo(minutes);
  return t.common.hoursAgo(Math.round(minutes / 60));
}

/** Local 24-hour clock time for a timestamp, such as "20:41". */
export function formatClockTime(iso: string, locale: Locale): string {
  const time = Date.parse(iso);
  return Number.isFinite(time) ? new Date(time).toLocaleTimeString(INTL_TAGS[locale], { hour: '2-digit', minute: '2-digit' }) : '';
}
