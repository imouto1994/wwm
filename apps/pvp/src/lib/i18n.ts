// All user-facing text, in one mapping per locale. English defines the shape;
// Vietnamese must match it key for key (and parameter for parameter), so a
// missing translation is a type error. Vietnamese is the default because the
// guild plays in Vietnamese.
//
// Rules code (reducer, polls) never formats text itself: it returns a
// `Translatable`, a function the UI calls with the current messages, so errors
// show up in whichever language is selected when they're displayed.

export type Locale = 'vi' | 'en';
export const LOCALES: readonly Locale[] = ['vi', 'en'];
export const DEFAULT_LOCALE: Locale = 'vi';

type SeriesRef = Pick<Series, 'id' | 'stage'>;

function seriesNumber(series: SeriesRef): number {
  return Number.parseInt(series.id.slice(1), 10) || 1;
}

